  console.log('▶ Ricambi in garage');
  await C('vai', 'veicoli'); await p.waitForTimeout(500);
  esito('in Veicoli c\'è il tasto «Magazzino»', await p.evaluate(() => /Magazzino/.test(document.getElementById('tastoMagazzino').textContent)));
  await p.click('#tastoMagazzino'); await p.waitForTimeout(500);
  esito('il tasto apre la pagina Magazzino (e in basso resta acceso Veicoli)', await p.evaluate(() => !document.getElementById('vista-magazzino').classList.contains('hidden') && document.querySelector('.nav[aria-current="page"]').dataset.vista === 'veicoli'));
  await p.click('#vista-magazzino [data-click="nuovaScorta()"]'); await p.waitForTimeout(500);
  esito('il ricambio chiede per quale auto (senza «Tutti»)', await p.evaluate(() => { const o = [...document.querySelectorAll('#m_veicolo option')].map(x => x.value); return o.length === 2 && !o.includes(''); }));
  await scegli('#m_veicolo', 'panda01'); await p.fill('#m_nome', 'Olio 5W-30'); await p.fill('#m_quantita', '5'); await scegli('#m_unita', 'litri'); await p.fill('#m_minimo', '1');
  await scegli('#m_voce', 'olio'); await p.fill('#m_prezzo', '9'); await p.fill('#m_note', 'Scaffale in alto');
  esito('«Come si conta» è un selettore con pezzi, litri, kg, metri…', await p.evaluate(() => { const o = [...document.querySelectorAll('#m_unita option')].map(o => o.value); return ['pezzi', 'litri', 'kg', 'metri', 'paia'].every(x => o.includes(x)); }));
  await salva();
  let sc = await vivi('scorte');
  esito('il ricambio è salvato, della Panda', sc.length === 1 && sc[0].quantita === 5 && sc[0].voce === 'olio' && sc[0].unita === 'litri' && sc[0].veicolo === 'panda01' && sc[0].prezzo === 9 && sc[0].note === 'Scaffale in alto');
  esito('nel Magazzino è sotto il nome dell\'auto', await p.evaluate(() => /Panda\s*Olio 5W-30/.test(document.getElementById('elencoMagazzino').innerText)));
  esito('si vede con i litri e dove si trova', await p.evaluate(() => /5 litri · per olio motore · Scaffale in alto/.test(document.getElementById('elencoMagazzino').textContent)));
  esito('valore del magazzino: 45 €', await p.evaluate(() => /45 €/.test(document.getElementById('numeriMagazzino').textContent)));
  await p.click('#vista-magazzino .chip[data-p*="golf01"]'); await p.waitForTimeout(300);
  esito('filtrando la Golf non c\'è', await p.evaluate(() => /Nessun ricambio per quest'auto/.test(document.getElementById('elencoMagazzino').textContent)));
  await p.click('#vista-magazzino .chip[data-p*=\'""]\']'); await p.waitForTimeout(300);
  await p.click('#elencoMagazzino .pm[aria-label^="Uno in più"]'); await p.waitForTimeout(300);
  esito('+ aggiunge uno', (await vivi('scorte'))[0].quantita === 6);
  await p.click('#elencoMagazzino .pm[aria-label^="Uno in meno"]'); await p.waitForTimeout(300);
  esito('− toglie uno', (await vivi('scorte'))[0].quantita === 5);

  await p.evaluate(() => window.__indietroNativo()); await p.waitForTimeout(400);
  esito('Indietro dal Magazzino torna a Veicoli', await p.evaluate(() => !document.getElementById('vista-veicoli').classList.contains('hidden')));
  await C('apriVeicolo', 'panda01'); await p.waitForTimeout(400);
  esito('nella scheda della Panda c\'è il ricambio', await p.evaluate(() => /Ricambi in garage/.test(document.getElementById('schedaCorpo').textContent) && /Olio 5W-30/.test(document.getElementById('schedaCorpo').textContent)));
  await p.click('#schedaCorpo .pm[aria-label^="Uno in più"]'); await p.waitForTimeout(300);
  esito('+ nella scheda aggiorna la riga senza chiuderla', (await vivi('scorte'))[0].quantita === 6 && await p.evaluate(() => /6 litri/.test(document.getElementById('schedaCorpo').textContent)) && await aperta('finScheda'));
  await p.click('#schedaCorpo .pm[aria-label^="Uno in meno"]'); await p.waitForTimeout(300);
  await p.evaluate(() => window.__indietroNativo()); await p.waitForTimeout(400);
  await C('apriVeicolo', 'golf01'); await p.waitForTimeout(400);
  esito('nella scheda della Golf non c\'è', await p.evaluate(() => !/Olio 5W-30/.test(document.getElementById('schedaCorpo').textContent)));
  await p.evaluate(() => window.__indietroNativo()); await p.waitForTimeout(400);
  console.log('▶ Dopo un intervento');
  await C('nuovoInterventoPer', 'panda01'); await p.waitForTimeout(500);
  await p.click('#m_voci [data-voce="olio"]'); await p.fill('#m_costo', '80');
  await salva(); await p.waitForTimeout(900);
  esito('arriva «Già che ci sei»', await aperta('finModulo') && await p.evaluate(() => document.getElementById('moduloTitolo').textContent === 'Già che ci sei'));
  const chiavi = await p.evaluate(() => [...document.querySelectorAll('#moduloCampi [id^="m_a_"], #moduloCampi [id^="m_s_"]')].map(e => e.id));
  esito('chiede delle 2 cose in lista e dell\'olio in garage', chiavi.filter(k => k.startsWith('m_a_')).length === 2 && chiavi.filter(k => k.startsWith('m_s_')).length === 1, chiavi.join(','));
  const primo = chiavi.find(k => k.startsWith('m_a_')); await p.click('#' + primo);
  await p.fill('#' + chiavi.find(k => k.startsWith('m_s_')), '4');
  await salva();
  ap = await vivi('appunti'); sc = await vivi('scorte');
  esito('una cosa segnata sistemata, l\'altra resta', ap.filter(a => a.fatto).length === 1 && ap.filter(a => !a.fatto).length === 1);
  esito('l\'olio in garage scende a 1', sc[0].quantita === 1);
  const ultimo = await p.evaluate(() => DC.vivi('interventi').filter(i => i.veicolo === 'panda01' && i.voci.includes('olio')).sort((a, b) => b.mod - a.mod)[0]);
  esito('il costo dei 4 litri (36 €) si aggiunge all\'intervento: 116 €', ultimo.costo === 116 && /Ricambi dal magazzino: Olio 5W-30 × 4/.test(ultimo.note), ultimo.costo + ' ' + ultimo.note);
  await C('vai', 'magazzino'); await p.waitForTimeout(400);
  esito('nel Magazzino «Da ricomprare» viene per primo', await p.evaluate(() => /^Da ricomprare\s*Olio 5W-30/.test(document.getElementById('elencoMagazzino').innerText.trim())));
  await p.evaluate(() => { window.__testoCondiviso = ''; window.__condividi = async o => { window.__testoCondiviso = o.testo; }; });
  await p.click('#vista-magazzino [data-click="listaSpesa()"]'); await p.waitForTimeout(300);
  esito('«Lista della spesa» prepara il testo da mandare', await p.evaluate(() => /Da comprare per l'auto:\n- Olio 5W-30 \(Panda\) — ne resta 1 litro/.test(window.__testoCondiviso)), await p.evaluate(() => window.__testoCondiviso));
  await p.evaluate(() => { delete window.__condividi; });
  const av = await p.evaluate(() => DC.avvisiHome().map(a => a.t));
  esito('in Home: «Da ricomprare: Olio 5W-30» che porta al Magazzino', av.some(t => /Da ricomprare: Olio 5W-30/.test(t)) && await p.evaluate(() => DC.avvisiHome().find(a => /Da ricomprare/.test(a.t)).vai === 'magazzino'));
  await C('nuovoInterventoPer', 'golf01'); await p.waitForTimeout(500);
  await p.click('#m_voci [data-voce="olio"]'); await salva(); await p.waitForTimeout(900);
  esito('cambio olio della Golf: l\'olio della Panda non c\'entra, non chiede', !(await aperta('finModulo')));

