  const att = await p.evaluate(() => { const c = DC.consumi('panda01').kmL; const r = DC.vivi('rifornimenti').filter(r => r.veicolo === 'panda01' && r.quantita && r.costo).sort((a, b) => a.data < b.data ? 1 : -1)[0]; return { c, pz: r.costo / r.quantita }; });
  await p.fill('#m_km', '150'); await p.fill('#m_persone', '3'); await p.fill('#m_pedaggi', '12');
  await salva(); await p.waitForTimeout(600);
