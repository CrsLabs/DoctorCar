  const atteso = 300 / (Math.round(att.c * 10) / 10) * att.pz + 12;
  const letto = Number(ris.e.replace(/[^\d,]/g, '').replace(',', '.'));
  esito('mostra il totale (andata e ritorno, consumo e prezzo dei pieni)', Math.abs(letto - atteso) < 0.02, ris.e + ' atteso ' + atteso.toFixed(2));
  esito('dice il costo a testa in 3', /A testa, in 3: /.test(ris.x));
  await p.click('#domandaSi'); await p.waitForTimeout(400);
  await p.click('[data-click="costoViaggio()"]'); await p.waitForTimeout(500);
