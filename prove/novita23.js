  esito('con consumo e prezzo scritti a mano: 100 km solo andata = 10,00 €', /10,00/.test(await p.evaluate(() => document.getElementById('domandaTitolo').textContent)));
  await p.click('#domandaSi'); await p.waitForTimeout(400);
  // consumo obbligatorio, in km/l oppure l/100 km
