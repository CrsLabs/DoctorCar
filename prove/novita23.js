  await salva();
  let ap = await vivi('appunti');
  esito('la cosa è salvata e aperta', ap.length === 1 && !ap[0].fatto && ap[0].veicolo === 'panda01');
  await C('apriVeicolo', 'panda01'); await p.waitForTimeout(400);
  esito('compare nella scheda', await p.evaluate(() => /Rumore dalla ruota/.test(document.getElementById('schedaCorpo').textContent)));
  esito('va nel foglio per l\'officina', await p.evaluate(() => /Da far vedere:\n- Rumore dalla ruota/.test(DC.testoOfficina(DC.veicoli().find(v => v.id === 'panda01')))));
  await p.evaluate(() => window.__indietroNativo()); await p.waitForTimeout(400);
  await C('apriControlli', 'panda01'); await p.waitForTimeout(500);
  await p.click('#m_c_olio'); await p.fill('#m_note', 'Spia del motore accesa a volte');
  await salva();
  ap = await vivi('appunti');
  esito('i controlli veloci con «Qualcosa da sistemare» aggiungono alla lista', ap.length === 2 && ap.some(a => /Spia del motore/.test(a.testo)));
